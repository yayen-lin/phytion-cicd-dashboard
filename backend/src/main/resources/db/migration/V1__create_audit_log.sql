-- Every action taken through the dashboard: who did what, to what, when, and how it went.
-- Rows are only ever added, never changed or deleted.
-- environment and version are set for deploys, promotions and rollbacks, and null for other actions.
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100)             NOT NULL,
    action_type   VARCHAR(50)              NOT NULL,
    target        VARCHAR(200)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    action_result VARCHAR(20)              NOT NULL,
    build_id      VARCHAR(50),
    details       VARCHAR(1000),
    environment   VARCHAR(50),
    version       VARCHAR(50)
);
