-- Dashboard users. Users are deactivated instead of deleted, so the audit log's usernames keep pointing to someone.
-- password_hash holds a BCrypt hash with its encoder prefix, e.g. {bcrypt}$2a$10$..., never the password itself.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100)             NOT NULL UNIQUE,
    password_hash VARCHAR(100)             NOT NULL,
    role          VARCHAR(20)              NOT NULL CHECK (role IN ('VIEWER', 'DEVELOPER', 'ADMIN')),
    active        BOOLEAN                  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
